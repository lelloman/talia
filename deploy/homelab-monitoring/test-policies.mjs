import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const load=name=>Function('return ('+readFileSync(new URL(name,import.meta.url),'utf8')+')')();
const policy=load('condition.js'),guard=load('availability.js');
let now=100000,sample={hasValue:true,quality:'good',timestamp:now,value:{checked:now,series:[]}};
const ctx={state:{},params:{name:'Test',summary:'{{ $labels.instance }}',description:'{{ $value }} failures',forMs:60000,staleMs:45000,severity:'warning'},now:()=>now,read:async()=>sample};
const step=async(dt,series)=>{now+=dt;sample.timestamp=now;sample.value={checked:now,series};return policy.evaluate(ctx);};
const a={labels:{instance:'a'},value:101},b={labels:{instance:'b'},value:102};
assert.equal((await step(0,[a])).active,false);
assert.equal((await step(30000,[a,b])).active,false);
assert.equal((await step(30000,[a,b])).active,true);
const first=(await step(0,[a,b])).stage;
assert.equal((await step(30000,[a,b])).stage,first==='firing-a'?'firing-b':'firing-a');
assert.equal((await step(0,[])).active,false);
await step(0,[a]);assert.equal((await step(60000,[a])).active,false,'sampling gaps reset pending time');
sample.quality='error';await assert.rejects(policy.evaluate(ctx));
const health={...ctx,state:{}};
assert.equal((await guard.evaluate(health)).active,false);now+=120000;
assert.equal((await guard.evaluate(health)).active,true);
sample.quality='good';sample.timestamp=now;assert.equal((await guard.evaluate(health)).active,false);
ctx.params.forMs=0;assert.equal((await step(0,[a])).active,true);
assert.match((await step(0,[a])).message,/101 failures/);
assert.equal((await step(0,[])).active,false);
console.log('Policy checks passed: durations, per-series timing, membership changes, recovery, gaps, unavailable input, immediate security alerts.');
